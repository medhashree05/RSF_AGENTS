import json
import os
import urllib.request
import urllib.error
from abc import ABC, abstractmethod
from typing import Any, Callable, Dict, List, Optional, Union
from pydantic import BaseModel, Field


class TokenUsage(BaseModel):
    """Detailed token usage accounting."""
    prompt_tokens: int = Field(default=0, description="Tokens in input messages")
    completion_tokens: int = Field(default=0, description="Tokens generated by model")
    total_tokens: int = Field(default=0, description="Total tokens consumed")


class LLMResponse(BaseModel):
    """Normalized response returned from an LLMProvider."""
    content: str = Field(..., description="Raw text response generated by LLM")
    model: str = Field(default="unknown-model", description="Model identifier")
    usage: Optional[TokenUsage] = Field(default=None, description="Token usage counts if provided")
    cost_usd: Optional[float] = Field(default=None, description="Calculated API cost in USD if reliably available")
    raw: Optional[Dict[str, Any]] = Field(default=None, description="Raw provider response payload")


class LLMError(Exception):
    """Base exception for LLM provider errors."""
    pass


class LLMTimeoutError(LLMError):
    """Raised when an LLM request exceeds configured timeout."""
    pass


class LLMRateLimitError(LLMError):
    """Raised when the LLM provider returns a 429 Rate Limit error."""
    pass


class LLMAuthError(LLMError):
    """Raised when provider credentials are missing or invalid."""
    pass


class LLMProvider(ABC):
    """Abstract interface decoupling agent logic from specific LLM providers."""

    @abstractmethod
    def generate(self, messages: List[Dict[str, str]], **kwargs) -> LLMResponse:
        """
        Generate completion for a sequence of conversation messages.
        
        Args:
            messages: List of message dicts: [{"role": "system"|"user"|"assistant", "content": "..."}]
            
        Returns:
            LLMResponse containing text content, model name, and optional token usage.
        """
        pass

    @abstractmethod
    def get_model_name(self) -> str:
        """Return identifier of model being utilized."""
        pass


class MockLLMProvider(LLMProvider):
    """
    Deterministic mock provider for offline testing without network access or API keys.
    Supports fixed responses, queued sequences, and exception injection.
    """
    def __init__(
        self,
        responses: Optional[List[Union[str, LLMResponse, Exception]]] = None,
        responder: Optional[Callable[[List[Dict[str, str]]], Union[str, LLMResponse]]] = None,
        model_name: str = "mock-swe-agent-v1",
        default_cost_usd: Optional[float] = None,
    ):
        self.model_name = model_name
        self.responses: List[Union[str, LLMResponse, Exception]] = list(responses) if responses else []
        self.responder = responder
        self.default_cost_usd = default_cost_usd
        self.call_history: List[List[Dict[str, str]]] = []
        self.call_count: int = 0

    def get_model_name(self) -> str:
        return self.model_name

    def queue_response(self, response: Union[str, LLMResponse, Exception]):
        """Enqueue an additional response or exception."""
        self.responses.append(response)

    def generate(self, messages: List[Dict[str, str]], **kwargs) -> LLMResponse:
        self.call_history.append(messages)
        self.call_count += 1

        if self.responses:
            item = self.responses.pop(0)
            if isinstance(item, Exception):
                raise item
            if isinstance(item, LLMResponse):
                return item
            return LLMResponse(
                content=item,
                model=self.model_name,
                usage=TokenUsage(
                    prompt_tokens=sum(len(m.get("content", "").split()) for m in messages),
                    completion_tokens=len(item.split()),
                    total_tokens=sum(len(m.get("content", "").split()) for m in messages) + len(item.split())
                ),
                cost_usd=self.default_cost_usd
            )

        if self.responder:
            result = self.responder(messages)
            if isinstance(result, LLMResponse):
                return result
            return LLMResponse(
                content=result,
                model=self.model_name,
                usage=TokenUsage(prompt_tokens=100, completion_tokens=50, total_tokens=150),
                cost_usd=self.default_cost_usd
            )

        # Default fallback response: submit immediately
        fallback_json = json.dumps({
            "action": "submit",
            "args": {"summary": "Mock task complete."},
            "declared_scope": {"write": [], "read": [], "network": False}
        })
        return LLMResponse(
            content=fallback_json,
            model=self.model_name,
            usage=TokenUsage(prompt_tokens=50, completion_tokens=20, total_tokens=70),
            cost_usd=self.default_cost_usd
        )


class OpenAILikeProvider(LLMProvider):
    """
    Standard HTTP-based provider compatible with OpenAI-style chat completions API.
    Uses standard library urllib to avoid requiring heavy third-party dependencies.
    """
    def __init__(
        self,
        model_name: str = "gpt-4o-mini",
        api_key_env_var: str = "OPENAI_API_KEY",
        base_url: str = "https://api.openai.com/v1/chat/completions",
        timeout: float = 60.0,
    ):
        self.model_name = model_name
        self.api_key_env_var = api_key_env_var
        self.base_url = base_url
        self.timeout = timeout

    def get_model_name(self) -> str:
        return self.model_name

    def generate(self, messages: List[Dict[str, str]], **kwargs) -> LLMResponse:
        api_key = os.getenv(self.api_key_env_var)
        if not api_key:
            raise LLMAuthError(
                f"Missing API key in environment variable '{self.api_key_env_var}'. "
                f"Set it or switch to MockLLMProvider for offline execution."
            )

        payload = {
            "model": self.model_name,
            "messages": messages,
            "temperature": kwargs.get("temperature", 0.0),
        }
        data = json.dumps(payload).encode("utf-8")
        headers = {
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}"
        }

        req = urllib.request.Request(self.base_url, data=data, headers=headers, method="POST")

        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                status_code = resp.getcode()
                raw_body = resp.read().decode("utf-8")
                res_json = json.loads(raw_body)
                
                content = res_json["choices"][0]["message"]["content"]
                usage_raw = res_json.get("usage", {})
                usage = TokenUsage(
                    prompt_tokens=usage_raw.get("prompt_tokens", 0),
                    completion_tokens=usage_raw.get("completion_tokens", 0),
                    total_tokens=usage_raw.get("total_tokens", 0)
                ) if usage_raw else None

                return LLMResponse(
                    content=content,
                    model=res_json.get("model", self.model_name),
                    usage=usage,
                    cost_usd=None,  # Price catalog not hardcoded; left explicitly None
                    raw=res_json
                )
        except urllib.error.HTTPError as e:
            if e.code == 429:
                raise LLMRateLimitError(f"HTTP 429 Rate Limit exceeded: {e.reason}")
            elif e.code in (401, 403):
                raise LLMAuthError(f"HTTP {e.code} Authentication error: {e.reason}")
            else:
                raise LLMError(f"HTTP {e.code} error from LLM provider: {e.reason}")
        except urllib.error.URLError as e:
            if isinstance(e.reason, TimeoutError) or "timed out" in str(e.reason).lower():
                raise LLMTimeoutError(f"Request to LLM provider timed out: {e.reason}")
            raise LLMError(f"Network error contacting LLM provider: {e.reason}")
        except Exception as e:
            raise LLMError(f"Unexpected error in LLM provider: {e}")
